namespace quiz_archiver;

// @codingStandardsIgnoreLine
global $CFG;

require_once($CFG->dirroot . '/mod/quiz/locallib.php');
require_once($CFG->dirroot . '/mod/quiz/report/reportlib.php');
require_once($CFG->dirroot . '/mod/quiz/report/archiver/report.php');

/**
 * Tests for the GET-based alerts on the quiz archiver report page
 */
final class report_alert_test extends \advanced_testcase {
    /**
     * Renders the report page with the given GET parameters
     *
     * @param array $params GET parameters as received by PHP
     * @return string Rendered HTML
     */
    protected function render_report_page(array $params): string {
        global $PAGE;

        $this->resetAfterTest();
        $this->setAdminUser();
        $course = $this->getDataGenerator()->create_course();
        $quiz = $this->getDataGenerator()->create_module('quiz', ['course' => $course->id]);
        $cm = get_coursemodule_from_id('quiz', $quiz->cmid);
        $PAGE->set_url(new \moodle_url('/mod/quiz/report.php', ['id' => $cm->id, 'mode' => 'archiver']));
        $PAGE->set_cm($cm, $course);

        $_GET = $params;
        ob_start();
        (new \quiz_archiver_report())->display($quiz, $cm, $course);
        return ob_get_clean();
    }

    #[\PHPUnit\Framework\Attributes\Group('baseline')]
    /**
     * Tests that double-encoded markup in the alert parameters is not rendered
     *
     * @covers \quiz_archiver_report::display
     *
     * @return void
     */
    public function test_alert_does_not_render_injected_markup(): void {
        $html = $this->render_report_page([
            'al' => 'error',
            'asid' => 'a',
            'aa' => '%3Ca%20href%3D%22https%3A%2F%2Fattacker.example%2F%22%3EInjected%3C%2Fa%3E',
        ]);

        $this->assertStringNotContainsString('href="https://attacker.example/"', $html);
    }

    #[\PHPUnit\Framework\Attributes\Group('baseline')]
    /**
     * Tests that an alert URL generated by the report is displayed as intended
     *
     * @covers \quiz_archiver_report::display
     *
     * @return void
     */
    public function test_alert_from_generated_url_is_displayed(): void {
        $jobid = '00000000-1234-5678-abcd-ef4242424242';
        $report = new \quiz_archiver_report();
        (new \ReflectionProperty($report, 'cm'))->setValue($report, (object) ['id' => 1]);
        $method = new \ReflectionMethod($report, 'base_url_with_alert');
        $alerturl = $method->invoke($report, 'success', true, 'job_created_successfully', $jobid);

        // PHP decodes the query string once before the parameters reach optional_param().
        parse_str(parse_url($alerturl->out(false), PHP_URL_QUERY), $params);
        $html = $this->render_report_page($params);

        $this->assertStringContainsString(get_string('job_created_successfully', 'quiz_archiver', $jobid), $html);
    }
}
